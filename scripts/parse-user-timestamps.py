def parse_time(ts: str) -> float:
    # "00:00.82" -> float seconds
    parts = ts.split(":")
    mins = float(parts[0])
    secs = float(parts[1])
    return round(mins * 60 + secs, 2)

phrases = []
idx = 1
for line in raw_data:
    line = line.strip()
    if not line:
        continue
    # Line format: "[00:00.00 – 00:00.82] text"
    bracket_end = line.find("]")
    time_part = line[1:bracket_end]
    text = line[bracket_end+1:].strip()
    
    # Handle en-dash or hyphen
    if "–" in time_part:
        start_str, end_str = time_part.split("–")
    else:
        start_str, end_str = time_part.split("-")
        
    s = parse_time(start_str.strip())
    e = parse_time(end_str.strip())
    
    phrases.append({
        "id": f"p{idx:02d}",
        "text": text,
        "s": s,
        "e": e
    })
    idx += 1

